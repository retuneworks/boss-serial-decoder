let language = 'ja';

function savedLanguage() {
  try { return localStorage.getItem('site-language'); } catch { return null; }
}

export function getLanguage() { return language; }

export function translate(key) {
  return translations[language]?.[key] || translations.ja[key] || key;
}

function applyLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = translate(element.dataset.i18nPlaceholder);
  });

  const toggle = document.querySelector('#language-toggle');
  if (toggle) {
    toggle.textContent = language === 'ja' ? 'English' : '日本語';
    toggle.setAttribute('aria-label', language === 'ja' ? 'Switch to English' : '日本語に切り替える');
    toggle.setAttribute('lang', language === 'ja' ? 'en' : 'ja');
  }

  const page = document.body.dataset.page;
  if (page === 'home') {
    document.title = language === 'ja'
      ? 'BOSSコンパクトエフェクター 製造年月検索｜非公式'
      : 'BOSS Compact Pedal Manufacture Date Finder | Unofficial';
  } else if (page === 'about') {
    document.title = language === 'ja'
      ? 'このサイトについて｜BOSS製造年月検索'
      : 'About | BOSS Manufacture Date Finder';
  } else if (page === 'not-found') {
    document.title = language === 'ja' ? 'ページが見つかりません' : 'Page not found';
  }
}

export function setLanguage(nextLanguage) {
  language = nextLanguage === 'en' ? 'en' : 'ja';
  try { localStorage.setItem('site-language', language); } catch { /* storage is optional */ }
  applyLanguage();
  window.dispatchEvent(new CustomEvent('site-language-change', { detail: { language } }));
}

function initLanguage() {
  language = savedLanguage() === 'en' ? 'en' : 'ja';
  applyLanguage();
  document.querySelector('#language-toggle')?.addEventListener('click', () => {
    setLanguage(language === 'ja' ? 'en' : 'ja');
  });
}

if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initLanguage);
else initLanguage();
